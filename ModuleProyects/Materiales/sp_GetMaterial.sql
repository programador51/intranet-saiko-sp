CREATE PROCEDURE sp_GetMaterial(
    @idMaterial INT
) AS 
BEGIN

    SET LANGUAGE Spanish;
    SET NOCOUNT ON
    SELECT * FROM Materials WHERE id = @idMaterial;

END

